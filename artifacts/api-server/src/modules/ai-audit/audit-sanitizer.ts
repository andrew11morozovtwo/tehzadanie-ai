import type { AuditReport } from "./types";

type RedactionContext = {
  clientEmail: string;
  clientName: string;
};

const sensitiveKeyPattern =
  /(?:pass(?:word|phrase)?|secret|token|api[_ -]?key|authorization|credential|private[_ -]?key|cookie|session|address|passport|inn|snils|tax[_ -]?id)/iu;

function escapeRegExp(value: string): string {
  return value.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}

export function redactAuditText(value: string, context: RedactionContext): string {
  let redacted = value;
  if (context.clientName.trim().length > 1) {
    redacted = redacted.replace(new RegExp(escapeRegExp(context.clientName), "giu"), "[КЛИЕНТ]");
  }
  if (context.clientEmail) {
    redacted = redacted.replace(new RegExp(escapeRegExp(context.clientEmail), "giu"), "[EMAIL]");
  }
  return redacted
    .replace(
      /-----BEGIN (?:[A-Z ]*PRIVATE KEY|OPENSSH PRIVATE KEY)-----[\s\S]*?-----END (?:[A-Z ]*PRIVATE KEY|OPENSSH PRIVATE KEY)-----/gu,
      "[PRIVATE_KEY_REDACTED]",
    )
    .replace(/\bBearer\s+[A-Za-z0-9._~-]+\b/giu, "Bearer [REDACTED]")
    .replace(/\beyJ[A-Za-z0-9_-]+\.[A-Za-z0-9_-]+\.[A-Za-z0-9_-]+\b/gu, "[JWT_REDACTED]")
    .replace(/\bsk-[A-Za-z0-9_-]{16,}\b/gu, "[API_KEY_REDACTED]")
    .replace(/\b(?:sk|pk|rk|re)_[A-Za-z0-9_-]{16,}\b/gu, "[API_KEY_REDACTED]")
    .replace(/\bAIza[A-Za-z0-9_-]{20,}\b/gu, "[API_KEY_REDACTED]")
    .replace(/\b(?:gh[pousr]|github_pat)_[A-Za-z0-9_-]{20,}\b/gu, "[API_KEY_REDACTED]")
    .replace(/\bxox[baprs]-[A-Za-z0-9-]{10,}\b/gu, "[API_KEY_REDACTED]")
    .replace(/\bGOCSPX-[A-Za-z0-9_-]{10,}\b/gu, "[API_KEY_REDACTED]")
    .replace(/\b(?:AKIA|ASIA)[A-Z0-9]{16}\b/gu, "[API_KEY_REDACTED]")
    .replace(/\b[A-Z0-9._%+-]+@[A-Z0-9.-]+\.[A-Z]{2,}\b/giu, "[EMAIL]")
    .replace(/\+?\d[\d\s().-]{8,}\d/gu, "[PHONE]")
    .replace(
      /\b(?:паспорт|инн|снилс|ssn|tax[ _-]?id)\s*[:№#-]?\s*[A-Za-zА-Яа-яЁё0-9 -]{5,}/giu,
      "[IDENTIFIER_REDACTED]",
    )
    .replace(
      /(?:ул\.?|улица|проспект|пр-т|переулок|шоссе|бульвар|наб\.?|набережная|street|st\.?|avenue|ave\.?|road|rd\.?)\s+[^\n.!?]{1,80}(?=[\n.!?]|$)/giu,
      "[ADDRESS_REDACTED]",
    )
    .replace(
      /([?&](?:password|token|secret|api[_-]?key|authorization)=)[^&\s]+/giu,
      "$1[REDACTED]",
    )
    .replace(
      /\b(password|passphrase|token|secret|api[_ -]?key|authorization)\s*[:=]\s*([^\s,;]+)/giu,
      "$1=[REDACTED]",
    );
}

export function redactAuditValue(value: unknown, context: RedactionContext): unknown {
  if (typeof value === "string") return redactAuditText(value, context);
  if (Array.isArray(value)) return value.map((item) => redactAuditValue(item, context));
  if (value && typeof value === "object") {
    return Object.fromEntries(
      Object.entries(value).map(([key, item]) => [
        key,
        sensitiveKeyPattern.test(key) ? "[REDACTED]" : redactAuditValue(item, context),
      ]),
    );
  }
  return value;
}

export function redactAuditReport(report: AuditReport, context: RedactionContext): AuditReport {
  const redacted = redactAuditValue(
    {
      ...report,
      audit_metadata: {},
    },
    context,
  ) as AuditReport;
  return {
    ...redacted,
    // Metadata is generated by the server after model validation. It contains
    // a masked client email and operational timestamps, not source PII.
    audit_metadata: report.audit_metadata,
  };
}